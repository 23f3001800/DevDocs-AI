"""
RAGAS evaluation gate.

Answers are generated by the app's own Gemini provider, then scored by a
*separate, larger* Gemini model acting as judge.

⚠️  BIAS CAVEAT: judging a model's output with the same model family invites
self-preference bias — LLMs systematically rate their own generations higher.
Using a different, stronger model as judge (RAGAS_EVALUATOR_MODEL, defaulting to
gemini-2.5-pro while answers come from gemini-2.5-flash) mitigates this but does
not eliminate it. Treat the absolute scores as a regression signal over time,
not as a ground-truth measure of quality.
"""

import json
import logging
import os
import sys
from pathlib import Path

from app.config import configure_logging, get_settings

log = logging.getLogger(__name__)


def run_evals(threshold: float = 0.75) -> dict | None:
    configure_logging()
    settings = get_settings()

    # ── Pre-flight checks (soft-skip so forks without secrets stay green) ──
    if not settings.google_api_key:
        log.warning("GOOGLE_API_KEY not set — skipping RAGAS eval.")
        log.warning("Set the secret in GitHub → Settings → Secrets to enable.")
        sys.exit(0)

    from app.vectorstore import VectorStore

    vs = VectorStore()
    doc_count = vs.count()
    if doc_count == 0:
        log.warning("Vector store is empty — no documents ingested. Skipping eval (soft pass).")
        log.warning("Run: python -m scripts.ingest --source <source> first.")
        sys.exit(0)

    log.info("Vector store has %d chunks.", doc_count)

    # ── Lazy imports (only if we're actually running) ────────────
    from ragas import EvaluationDataset, SingleTurnSample, evaluate
    from ragas.metrics.collections import (
        AnswerRelevancy,
        ContextPrecision,
        Faithfulness,
    )

    from app.chain import ask
    from app.retriever_instance import get_retriever

    golden = json.loads(Path("tests/golden_set.json").read_text())
    retriever = get_retriever()

    samples = []
    for item in golden:
        q = item["question"]
        log.info("Evaluating: %s...", q[:60])
        try:
            chunks = retriever.retrieve(q, k=4)
            resp = ask(q)
            samples.append(
                SingleTurnSample(
                    user_input=q,
                    response=resp.answer,
                    retrieved_contexts=[c["content"] for c in chunks] or ["No context found."],
                    reference=item["ground_truth"],
                )
            )
        except Exception as e:
            log.warning("  Skipped (error: %s)", e)
            continue

    if not samples:
        log.error("All questions failed — cannot run RAGAS evaluation.")
        sys.exit(1)

    from langchain_google_genai import ChatGoogleGenerativeAI

    evaluator_model = os.getenv("RAGAS_EVALUATOR_MODEL", "gemini-2.5-pro")
    log.info("Judging with %s (answers generated by %s)", evaluator_model, settings.gemini_model)
    evaluator_llm = ChatGoogleGenerativeAI(
        model=evaluator_model,
        google_api_key=settings.google_api_key,
    )

    metrics = [
        # Faithfulness  → is every claim supported by the context? (hallucination)
        # AnswerRelevancy → does the answer address the question?
        # ContextPrecision → were the retrieved chunks actually relevant? (retrieval)
        Faithfulness(llm=evaluator_llm),
        AnswerRelevancy(llm=evaluator_llm),
        ContextPrecision(llm=evaluator_llm),
    ]

    result = evaluate(dataset=EvaluationDataset(samples=samples), metrics=metrics)

    scores = {
        "faithfulness": round(float(result["faithfulness"]), 4),
        "answer_relevancy": round(float(result["answer_relevancy"]), 4),
        "context_precision": round(float(result["context_precision"]), 4),
    }

    # WHY save to JSON? CI needs a persistent artefact to compare, so score
    # regressions across PRs are visible instead of silent.
    out = Path("docs/evaluation/ragas_results.json")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(scores, indent=2))

    print(f"\n{'=' * 40}")
    print(f"Faithfulness:      {scores['faithfulness']:.4f}")
    print(f"Answer Relevancy:  {scores['answer_relevancy']:.4f}")
    print(f"Context Precision: {scores['context_precision']:.4f}")

    avg = sum(scores.values()) / len(scores)
    print(f"Average:           {avg:.4f}  (threshold: {threshold})")

    if avg < threshold:
        print(f"\n❌ EVAL GATE FAILED — avg {avg:.4f} < {threshold}")
        sys.exit(1)  # non-zero exit blocks the CI deploy

    print(f"\n✅ Eval gate passed — {avg:.4f} ≥ {threshold}")
    return scores


if __name__ == "__main__":
    run_evals()
